export const getProductImage = (slug?: string, primaryImageUrl?: string, categoryName?: string): string => {
  if (primaryImageUrl && primaryImageUrl.startsWith('http')) {
    return primaryImageUrl;
  }
  if (slug && PRODUCT_UNIQUE_IMAGES[slug]) {
    return PRODUCT_UNIQUE_IMAGES[slug];
  }
  // Generic fallback if not matched
  const cat = (categoryName || '').toLowerCase();
  if (cat.includes('elect') || cat.includes('gadget') || cat.includes('phone') || cat.includes('laptop'))
    return 'https://images.unsplash.com/photo-1511707171634-5f897ff02aa9?w=600&auto=format&fit=crop&q=80';
  if (cat.includes('game') || cat.includes('console'))
    return 'https://images.unsplash.com/photo-1606813907291-d86efa9b94db?w=600&auto=format&fit=crop&q=80';
  if (cat.includes('sport') || cat.includes('fit'))
    return 'https://images.unsplash.com/photo-1584735935682-2f2b69dff9d2?w=600&auto=format&fit=crop&q=80';
  if (cat.includes('cloth') || cat.includes('apparel') || cat.includes('fashion'))
    return 'https://images.unsplash.com/photo-1441986300917-64674bd600d8?w=600&auto=format&fit=crop&q=80';
  if (cat.includes('beauty') || cat.includes('care'))
    return 'https://images.unsplash.com/photo-1522337360788-8b13dee7a37e?w=600&auto=format&fit=crop&q=80';
  if (cat.includes('watch') || cat.includes('access'))
    return 'https://images.unsplash.com/photo-1523275335684-37898b6baf30?w=600&auto=format&fit=crop&q=80';
  if (cat.includes('book') || cat.includes('stat'))
    return 'https://images.unsplash.com/photo-1544716278-ca5e3f4abd8c?w=600&auto=format&fit=crop&q=80';
  if (cat.includes('home') || cat.includes('living'))
    return 'https://images.unsplash.com/photo-1513694203232-719a280e022f?w=600&auto=format&fit=crop&q=80';
  return 'https://images.unsplash.com/photo-1505740420928-5e560c06d30e?w=600&auto=format&fit=crop&q=80';
};
